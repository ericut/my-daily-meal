CREATE TABLE IF NOT EXISTS sync_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source TEXT NOT NULL DEFAULT 'TheMealDB',
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ,
  status TEXT NOT NULL CHECK (status IN ('running','completed','failed')),
  records_seen INTEGER NOT NULL DEFAULT 0,
  next_cursor TEXT,
  message TEXT
);

CREATE TABLE IF NOT EXISTS categories (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  description TEXT,
  thumbnail_url TEXT,
  source_data JSONB NOT NULL DEFAULT '{}'::jsonb,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS areas (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  source_data JSONB NOT NULL DEFAULT '{}'::jsonb,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ingredients (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  description TEXT,
  thumbnail_url TEXT,
  source_data JSONB NOT NULL DEFAULT '{}'::jsonb,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS meals (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  category_id TEXT REFERENCES categories(id) ON UPDATE CASCADE,
  area_id TEXT REFERENCES areas(id) ON UPDATE CASCADE,
  instructions TEXT,
  thumbnail_url TEXT,
  tags TEXT[] NOT NULL DEFAULT '{}',
  source_url TEXT,
  youtube_url TEXT,
  creative_commons_confirmed BOOLEAN,
  source_data JSONB NOT NULL DEFAULT '{}'::jsonb,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS meal_ingredients (
  meal_id TEXT NOT NULL REFERENCES meals(id) ON DELETE CASCADE,
  ingredient_id TEXT NOT NULL REFERENCES ingredients(id) ON UPDATE CASCADE,
  position SMALLINT NOT NULL,
  measure TEXT NOT NULL DEFAULT '',
  PRIMARY KEY (meal_id, ingredient_id, position)
);
CREATE INDEX IF NOT EXISTS meal_ingredients_by_ingredient ON meal_ingredients (ingredient_id, meal_id);
CREATE INDEX IF NOT EXISTS meals_by_name ON meals (lower(name));

CREATE TABLE IF NOT EXISTS saved_searches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label TEXT,
  ingredient_ids TEXT[] NOT NULL DEFAULT '{}',
  match_mode TEXT NOT NULL DEFAULT 'all' CHECK (match_mode IN ('all','any')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS favorites (
  meal_id TEXT PRIMARY KEY REFERENCES meals(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS meal_plan_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  planned_for DATE NOT NULL,
  meal_id TEXT NOT NULL REFERENCES meals(id) ON DELETE CASCADE,
  meal_slot TEXT NOT NULL DEFAULT 'any',
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (planned_for, meal_slot, meal_id)
);
CREATE TABLE IF NOT EXISTS shopping_list_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ingredient_name TEXT NOT NULL,
  quantity TEXT,
  checked BOOLEAN NOT NULL DEFAULT false,
  source_meal_id TEXT REFERENCES meals(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
